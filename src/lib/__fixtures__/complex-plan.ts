function top(overrides: Partial<PlanMass["top"]> = {}): PlanMass["top"] {
  return {
    type: "flat",
    riseIn: 0,
    ridgeAxis: "x",
    overhangIn: 0,
    merlonWidthIn: 0,
    merlonGapIn: 0,
    merlonHeightIn: 0,
    notes: "",
    ...overrides,
  };
}

function mass(overrides: Partial<PlanMass> & Pick<PlanMass, "id" | "name" | "kind">): PlanMass {
  return {
    widthIn: 0,
    depthIn: 0,
    diameterIn: 0,
    heightIn: 0,
    xIn: 0,
    zIn: 0,
    baseYIn: 0,
    rotationDeg: 0,
    top: top(),
    materialNote: "",
    notes: "",
    ...overrides,
  };
}

